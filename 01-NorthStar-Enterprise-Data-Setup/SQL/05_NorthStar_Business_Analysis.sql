/*Profitability: Which products generate high sales but relatively low 
profit? Calculate a Profit Margin % using Profit Margin% = 
frac{ProfitAmount}{NetSales}\times100 */

/* Which products have Total Sales greater than the average Total Sales 
across all products?*/

WITH ProductPerformace_CTE
AS
(
	SELECT p.ProductName, SUM(NetSales) AS Total_Sales, SUM(ProfitAmount)
	AS Total_Profit, ROUND(SUM(ProfitAmount)/(NULLIF(SUM(NetSales),0)) 
	* 100,2) AS Percent_Profit_Margin
	FROM
	dbo.FactSales f
	INNER JOIN
	dbo.DimProduct p
	ON f.ProductKey = p.ProductKey
	GROUP BY ProductName
)
SELECT ProductName FROM ProductPerformace_CTE
WHERE Total_Sales > (SELECT 
AVG(Total_Sales) FROM ProductPerformace_CTE)

/*Which products generate high sales but relatively low profit?*/

WITH ProductPerformance_CTE
AS
(
	SELECT p.ProductName, SUM(NetSales) AS Total_Sales, SUM(ProfitAmount)
	AS Total_Profit, ROUND(SUM(ProfitAmount)/(NULLIF(SUM(NetSales),0)) 
	* 100,2) AS Percent_Profit_Margin
	FROM
	dbo.FactSales f
	INNER JOIN
	dbo.DimProduct p
	ON f.ProductKey = p.ProductKey
	GROUP BY ProductName
)
SELECT ProductName,
CASE
WHEN Total_Sales > (SELECT AVG(Total_Sales) FROM ProductPerformance_CTE)  
THEN 'High'
ELSE 'Low'
END AS SalesStatus,
CASE
WHEN Total_Profit < (SELECT AVG(Total_Profit) FROM ProductPerformance_CTE)  
THEN 'Low'
ELSE 'High'
END AS ProfitStatus
FROM ProductPerformance_CTE 

/*Employee performance: What are Net Sales and Profit generated by each 
employee?*/

SELECT e.EmployeeID, SUM(f.NetSales) AS Total_Sales, SUM(f.profitAmount)
AS Total_profit
FROM
dbo.FactSales f
INNER JOIN 
dbo.DimEmployee e
ON f.EmployeeKey = e.EmployeeKey
GROUP BY EmployeeID
ORDER BY SUM(f.NetSales) DESC;


/*Store performance: Compare Net Sales and Profit across stores*/

SELECT s.StoreName, SUM(f.NetSales) AS Total_Sales, SUM(f.ProfitAmount) AS
Total_Profit
FROM
dbo.DimStore s
INNER JOIN
dbo.FactSales f
ON s.StoreKey = f.StoreKey
GROUP BY s.StoreName
ORDER BY SUM(f.NetSales) DESC;


