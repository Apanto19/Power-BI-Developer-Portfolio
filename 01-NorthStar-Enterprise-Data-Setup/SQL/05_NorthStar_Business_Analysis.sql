/*Product performance: What are the top 10 products by Net Sales? Show 
Product Name, Quantity Sold, Net Sales, Cost and Profit.*/

SELECT Top 10 p.ProductName, SUM(f.Quantity) AS Total_Qty, 
SUM(f.NetSales) AS Total_Sales, SUM(f.CostAmount) AS Total_Cost, 
SUM(f.ProfitAmount) AS Total_Profit
FROM
dbo.DimProduct p
INNER JOIN
dbo.FactSales f
ON p.ProductKey = f.ProductKey
GROUP BY ProductName
ORDER BY SUM(f.NetSales) DESC;

