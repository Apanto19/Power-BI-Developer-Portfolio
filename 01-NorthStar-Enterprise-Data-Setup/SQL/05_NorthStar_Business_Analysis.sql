/*Sales vs returns: Which products sell strongly but also have unusually 
high returns?*/

WITH Sales_CTE AS
(
    SELECT
        ProductKey,
        SUM(NetSales) AS Total_Sales
    FROM dbo.FactSales
    GROUP BY ProductKey
),

Returns_CTE AS
(
    SELECT
        ProductKey,
        SUM(ReturnQty) AS Return_Vol
    FROM dbo.FactReturns
    GROUP BY ProductKey
),

ProductPerform_CTE AS
(
    SELECT
        p.ProductName,
        s.Total_Sales,
        ISNULL(r.Return_Vol, 0) AS Return_Vol
    FROM dbo.DimProduct p
    INNER JOIN Sales_CTE s
        ON p.ProductKey = s.ProductKey
    LEFT JOIN Returns_CTE r
        ON p.ProductKey = r.ProductKey
)

SELECT *
FROM ProductPerform_CTE
WHERE Total_Sales >
      (SELECT AVG(Total_Sales) FROM ProductPerform_CTE)
AND Return_Vol >
      (SELECT AVG(Return_Vol) FROM ProductPerform_CTE)
ORDER BY Total_Sales DESC;
